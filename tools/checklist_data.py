"""Write the combat assignments' objective list for the mod's Lua side.

usage: checklist_data.py <DataBuilder.exe> <vanilla root> <output .lua>

A combat assignment is a `Hub` row of Type 3. Its `WorldReportID` names a `WorldReport`
row, whose `MissionID_Array` lists the assignment's objectives. Each of those is a
`ReportMission` row carrying the story flag the game sets when that objective is met and
a `ConditionID`; the `ReportCondition` row it names carries the text key the game shows
and the arguments it fills in.

So "which objectives does this assignment have, and which are done" needs no engine call
beyond a story-flag read, which is what the mod already does for everything else. The
text key is written out as the game stores it; what the game draws for it is resolved at
runtime, since several of these texts take arguments (an enemy's ability, a count, a time)
that we do not reproduce here.
"""
from __future__ import annotations

import collections
import csv
import json
import subprocess
import sys
import tempfile
from pathlib import Path

TABLES = ("Hub", "WorldReport", "ReportMission", "ReportCondition")
COMBAT_ASSIGNMENT = "3"          # Hub.Type


def export(builder: str, vanilla: Path, out: Path) -> dict[str, dict[str, dict[str, str]]]:
    """Every table we need, as {table: {row: {property: value}}}."""
    tables: dict[str, dict[str, dict[str, str]]] = {}
    for name in TABLES:
        asset = vanilla / "End" / "Content" / "DataObject" / "Resident" / f"{name}.uasset"
        if not asset.is_file():
            raise SystemExit(f"missing {asset}")
        csv_path = out / f"{name}.csv"
        result = subprocess.run([builder, "export", str(asset), str(csv_path)],
                                capture_output=True, text=True)
        if result.returncode != 0:
            raise SystemExit(f"export {name} failed: {result.stderr.strip()[:200]}")
        rows: dict[str, dict[str, str]] = collections.defaultdict(dict)
        with open(csv_path, encoding="utf-8-sig", newline="") as handle:
            for row in csv.DictReader(handle):
                rows[row["Name"]][row["Property"]] = row["Value"]
        tables[name] = rows
    return tables


def assignments(tables) -> dict[str, dict]:
    hub, report = tables["Hub"], tables["WorldReport"]
    mission, condition = tables["ReportMission"], tables["ReportCondition"]
    out: dict[str, dict] = {}
    for name, row in sorted(hub.items()):
        if row.get("Type") != COMBAT_ASSIGNMENT:
            continue
        entry = report.get(row.get("WorldReportID", ""), {})
        objectives = []
        for mission_id in (entry.get("MissionID_Array") or "").split("|"):
            if not mission_id:
                continue
            mission_row = mission.get(mission_id, {})
            condition_row = condition.get(mission_row.get("ConditionID", ""), {})
            objectives.append({
                "mission": mission_id,
                "flag": mission_row.get("CompleteStoryFlag", ""),
                "key": condition_row.get("ViewString", ""),
                "condition": mission_row.get("ConditionID", ""),
            })
        if not objectives:
            continue
        out[name] = {
            "report": row.get("WorldReportID", ""),
            "title": entry.get("Title", ""),
            "header": entry.get("ObjectiveTextID", ""),
            "clear_flag": entry.get("CompleteFlag", ""),
            "objectives": objectives,
        }
    return out


def lua(data: dict[str, dict]) -> str:
    def quote(value: str) -> str:
        return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'

    lines = ["-- Generated by tools/checklist_data.py; do not edit by hand.",
             "-- Combat assignments (Hub.Type 3) and the objectives each one shows.",
             "return {"]
    for hub, entry in data.items():
        lines.append("  [%s] = {" % quote(hub))
        lines.append("    report = %s, title = %s," % (quote(entry["report"]), quote(entry["title"])))
        lines.append("    header = %s, clear_flag = %s," % (quote(entry["header"]), quote(entry["clear_flag"])))
        lines.append("    objectives = {")
        for objective in entry["objectives"]:
            lines.append("      { flag = %s, key = %s, condition = %s }," % (
                quote(objective["flag"]), quote(objective["key"]), quote(objective["condition"])))
        lines.append("    },")
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        raise SystemExit(__doc__.strip().splitlines()[2])
    builder, vanilla, output = argv[1], Path(argv[2]), Path(argv[3])
    with tempfile.TemporaryDirectory() as temporary:
        tables = export(builder, vanilla, Path(temporary))
    data = assignments(tables)
    keys = {objective["key"] for entry in data.values() for objective in entry["objectives"]}
    output.write_text(lua(data), encoding="utf-8")
    print(json.dumps({"assignments": len(data),
                      "objectives": sum(len(e["objectives"]) for e in data.values()),
                      "distinct_text_keys": len(keys), "written": str(output)}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
